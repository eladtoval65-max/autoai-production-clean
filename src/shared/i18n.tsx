const dicts: Record<Lang, Dict> = { he, en };

type Ctx = { lang: Lang; t: Dict; dir: "rtl" | "ltr"; setLang: (l: Lang) => void; nf: Intl.NumberFormat };
const LangContext = createContext<Ctx | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try { return (localStorage.getItem("autoai-lang") as Lang) === "en" ? "en" : "he"; } catch { return "he"; }
  });
  useEffect(() => {
    try { localStorage.setItem("autoai-lang", lang); } catch {}
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  }, [lang]);
  const value = useMemo<Ctx>(() => ({
    lang, setLang, t: dicts[lang], dir: lang === "he" ? "rtl" : "ltr",
    nf: new Intl.NumberFormat(lang === "he" ? "he-IL" : "en-US"),
  }), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): Ctx {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LangProvider");
  return ctx;
}

/** ₪ amount, always LTR-isolated so it survives inside Hebrew text. */
export function shekel(n: number | null | undefined, nf: Intl.NumberFormat): string {
  return n == null ? "–" : `⁦₪${nf.format(Math.round(n))}⁩`;
}
